#pragma once
#ifndef EEPROM_LAYOUT_H
#define EEPROM_LAYOUT_H

#include <Arduino.h>

#include "EepromSettings.h"

// EEPROM byte sizes
#define EEPROM_MAX_SIZE         512
#define CHECKSUM_SIZE           2
#define RESERVED_SIZE           100
#define WIFI_SSID_MAX_SIZE      32
#define WIFI_PASSWORD_MAX_SIZE  64
#define HOST_NAME_MAX_SIZE      32
#define MQTT_USER_MAX_SIZE      32
#define MQTT_PASSWORD_MAX_SIZE  64
#define NET_WD_TIMEOUT_SIZE     2
#define NET_WD_RECOVER_SIZE     2
#define MQTT_INTERVAL_SIZE      1
#define LOW_TEMP_SEC_ZONE_SIZE  1
#define SC_PREVENTION_SIZE      1
#define LWT_MAX_SIZE            4
#define VALVE_DELAY_SIZE        2
#define FLOOR_DELAY_SIZE        2
#define LWT_COOL_DOWN_SIZE      2
#define SC_SMALL_WINDOW_SIZE    2
#define SC_SMALL_COUNT_SIZE     1
#define SC_LARGE_WINDOW_SIZE    2
#define SC_LARGE_COUNT_SIZE     1
#define SC_RECOVERY_SIZE        2

// EEPROM locations
#define EEPROM_CHECKSUM       0                                                   // 0
#define EEPROM_WIFI_SSID      (EEPROM_CHECKSUM + CHECKSUM_SIZE)                   // 2
#define EEPROM_WIFI_PASSWORD  (EEPROM_WIFI_SSID + WIFI_SSID_MAX_SIZE + 1)         // 35
#define EEPROM_IP_ADDR        (EEPROM_WIFI_PASSWORD + WIFI_PASSWORD_MAX_SIZE + 1) // 100
#define EEPROM_IP_NETMASK     (EEPROM_IP_ADDR + EEPROM_IP_SIZE)                   // 104
#define EEPROM_MQTT_IP_ADDR   (EEPROM_IP_NETMASK + EEPROM_IP_SIZE)                // 108
#define EEPROM_MQTT_USER      (EEPROM_MQTT_IP_ADDR + EEPROM_IP_SIZE)              // 112
#define EEPROM_MQTT_PASSWORD  (EEPROM_MQTT_USER + MQTT_USER_MAX_SIZE + 1)         // 145
#define EEPROM_HOST_NAME      (EEPROM_MQTT_PASSWORD + MQTT_PASSWORD_MAX_SIZE + 1) // 210
#define EEPROM_CTRL_START     (EEPROM_HOST_NAME + HOST_NAME_MAX_SIZE + 1)         // 275 Controller settings start (erased by factory reset)
#define EEPROM_NET_WD_TIMEOUT (EEPROM_CTRL_START)                                 // 275
#define EEPROM_NET_WD_RECOVER (EEPROM_NET_WD_TIMEOUT + NET_WD_TIMEOUT_SIZE)       // 277
#define EEPROM_MQTT_INTERVAL  (EEPROM_NET_WD_RECOVER + NET_WD_RECOVER_SIZE)       // 279
#define EEPROM_LOW_TEMP_SEC_ZONE (EEPROM_MQTT_INTERVAL + MQTT_INTERVAL_SIZE)      // 280
#define EEPROM_SC_PREVENTION  (EEPROM_LOW_TEMP_SEC_ZONE + LOW_TEMP_SEC_ZONE_SIZE) // 281
#define EEPROM_LWT_MAX        (EEPROM_SC_PREVENTION + SC_PREVENTION_SIZE)         // 282
#define EEPROM_VALVE_DELAY    (EEPROM_LWT_MAX + LWT_MAX_SIZE)                     // 286
#define EEPROM_FLOOR_DELAY    (EEPROM_VALVE_DELAY + VALVE_DELAY_SIZE)             // 288
#define EEPROM_LWT_COOL_DOWN  (EEPROM_FLOOR_DELAY + FLOOR_DELAY_SIZE)             // 290
#define EEPROM_SC_SMALL_WINDOW (EEPROM_LWT_COOL_DOWN + LWT_COOL_DOWN_SIZE)        // 292
#define EEPROM_SC_SMALL_COUNT (EEPROM_SC_SMALL_WINDOW + SC_SMALL_WINDOW_SIZE)     // 294
#define EEPROM_SC_LARGE_WINDOW (EEPROM_SC_SMALL_COUNT + SC_SMALL_COUNT_SIZE)      // 295
#define EEPROM_SC_LARGE_COUNT (EEPROM_SC_LARGE_WINDOW + SC_LARGE_WINDOW_SIZE)     // 297
#define EEPROM_SC_RECOVERY    (EEPROM_SC_LARGE_COUNT + SC_LARGE_COUNT_SIZE)       // 298
#define EEPROM_RESERVED       (EEPROM_SC_RECOVERY + SC_RECOVERY_SIZE)             // 300
#define EEPROM_END            (EEPROM_RESERVED + RESERVED_SIZE)                   // 400

static_assert(EEPROM_END <= EEPROM_MAX_SIZE, "EEPROM layout exceeds EEPROM_MAX_SIZE");

#endif // EEPROM_LAYOUT_H
